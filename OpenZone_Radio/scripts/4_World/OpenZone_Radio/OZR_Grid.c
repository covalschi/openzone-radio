// Сітка рушія -- ВИМІРЯНА, а не переписана з конфігу нативного мода.
//
// Числа бази й кроку живуть у oz_frequencies.json поруч із DLL. Переписати їх
// сюди означало б завести другу копію, яка рано чи пізно розійдеться з першою
// -- і, розійшовшись, рахувала б частоти, яких у ефірі немає. OZR_Bands уже
// ходить по індексах і читає, що рушій СПРАВДІ повернув; звідси і база, і крок,
// і кількість беруться самі, і на непропатченому сервері теж (там це буде
// ванільна вісімка, і профілі просто нікуди не влізуть -- про що ми й скажемо).

class OZR_Grid
{
    static float Base()
    {
        return OZR_Bands.At(0);
    }

    // Крок беремо через ВЕСЬ проліт, а не через двох сусідів.
    //
    // Виміряно, не здогадка: різниця двох сусідів -- це віднімання двох близьких
    // великих float32, і воно з'їдає значущі цифри. Біля 136 МГц ulp у float32
    // близько 1.5e-5, тож 136.0125 - 136.0 дає 0.01249695 замість 0.0125 --
    // похибка в 0.02%, яка на 1280 діленнях накопичується в 4 кГц, і верх сітки
    // виходив 151.996 замість 152.000. Ділення прольоту на кількість проміжків
    // ту саму похибку не множить, а ділить.
    //
    // Рівномірність сітки при цьому лишається ПРИПУЩЕННЯМ, вірним лише для
    // нашої формули base + i*step; ванільна вісімка нерівномірна
    // (87.8 89.5 91.3 91.9 ...), тому Ready() нижче й існує.
    static float StepMHz()
    {
        int n = OZR_Bands.Count();
        if (n < 2)
            return 0;

        float span  = OZR_Bands.At(n - 1) - OZR_Bands.At(0);
        float gaps  = n - 1;
        return span / gaps;
    }

    static int Count()
    {
        return OZR_Bands.Count();
    }

    // Чи сітка взагалі придатна для профілів: рівномірна й достатньо частка.
    // Перевіряємо саме РІВНОМІРНІСТЬ, а не кількість: вісім ванільних частот
    // ідуть нерівними проміжками, і рахувати по них base + i*step -- значить
    // видавати числа, на які жодна рація не налаштується.
    static bool Ready()
    {
        int n = Count();
        if (n < 3)
            return false;

        float step = StepMHz();
        if (step <= 0)
            return false;

        // Допуск -- десята частина кроку: float32 на 150 МГц має ulp близько
        // 1e-5, тож похибка накопичення на тисячі ділень лишається дрібною
        // проти будь-якого осмисленого кроку.
        float tol = step * 0.1;

        for (int i = 2; i < n; i++)
        {
            float d = OZR_Bands.At(i) - OZR_Bands.At(i - 1);
            if (Math.AbsFloat(d - step) > tol)
                return false;
        }
        return true;
    }

    // МГц -> найближче ділення. Округлюємо, а не відкидаємо: 144.0 у float
    // цілком може виявитись 143.99998, і відкидання зсунуло б його на ділення
    // назад.
    static int IndexOf(float mhz)
    {
        float step = StepMHz();
        if (step <= 0)
            return 0;
        return Math.Round((mhz - Base()) / step);
    }

    static float MHzAt(int index)
    {
        return Base() + index * StepMHz();
    }

    static bool Holds(int index)
    {
        return index >= 0 && index < Count();
    }
}
