// Константи мода рації.

class OZR_Const
{
    static const string LOG_PREFIX = "[OpenZone/Radio] ";

    // Простір імен RPC. ВЛАСНИЙ, а не ядерний OZ_Const.MOD: рація працює й там,
    // де ядра немає, а рядок цей -- лише ключ, за яким CF розводить пакети.
    // Значення збігається з ядерним навмисне -- родина одна, і розводити її по
    // різних просторах немає за що.
    static const string MOD = "OpenZone";

    // Найбільший індекс каналу, який ще може дійти до гравця.
    //
    // ЦЕ НЕ ОЦІНКА І НЕ СМАК. Налаштований індекс їде на клієнт власною
    // синхрозмінною (див. OZR_Tuning: RegisterNetSyncVariableInt), а її
    // діапазон оголошується числом -- ось цим. Канал з більшим індексом існував
    // би на сервері й був би невидимий власникові рації: він стояв би на
    // частоті, якої не бачить. Тому це стеля і для виведення ефіру
    // (OZR_Ether.Derive відмовляє понад неї), і для проби нижче.
    //
    // Історія числа тут важлива, бо тут уже помилялись двічі. Спершу стояло 32
    // -- «завідомо більше за очікуване», коли відповіддю була вісімка. Потім
    // 4096 -- те саме припущення, тільки більше: сітка з нього не виводилась, а
    // вгадувалась, і сервер, що роздавав більше, мовчки мірявся обрізаним. Тепер
    // число не вгадане: воно дорівнює тому, що дозволяє синхронізація, і мусить
    // збігатися з нею посимвольно.
    static const int INDEX_MAX = 65535;

    // Довжина сплеску статики на відкриття й закриття ефіру.
    //
    // Ванільний набір -- зациклений шум, тож довжину задаємо ми. Сто сорок
    // мілісекунд -- це чутно як «клац», а не як увімкнений шум: коротше
    // губиться, довше починає читатись як несправність рації.
    static const int SQUELCH_MS = 140;

    // Наш набір, а не ванільний: ванільний тихий за задумом (volume = 0.0501,
    // range = 13 -- фоновий шип увімкненої рації). Наш успадковує його семпл
    // і піднімає рівень; див. CfgSoundShaders у config.cpp.
    static const string SQUELCH_SET = "OZR_Squelch_SoundSet";

    // Клас предмета, на якому міряємо таблицю частот. Ванільна рація --
    // єдиний ItemTransmitter, який точно є на будь-якому сервері.
    static const string BAND_PROBE_CLASS = "PersonalRadio";

    // Власні налаштування мода. Поки що в них одне поле -- вимикач діагностики.
    //
    // ІМ'Я НОВЕ, і це не смак. Radio.json уже існує на серверах і належить
    // спискові каналів КПК; зайняти його своїми полями означало б ЗАТЕРТИ
    // чужі дані на першому ж старті -- що тут одного разу й сталося, поки
    // файл називався так. Нову річ називають новим іменем.
    static const string SETTINGS      = "$profile:OpenZone\\OZ_Radio_Settings.json";
    // 2 -- додано підсилення сплеску й голосу (SquelchGain, VoiceGain).
    static const int    SCHEMA_RADIO  = 2;

    // Профілі ручних рацій: діапазон і крок на класнейм. Окремий файл, бо це
    // окреме рішення адміна -- канали КПК і те, куди дістає ручна рація, не
    // мають нічого спільного, крім ефіру.
    static const string PROFILES         = "$profile:OpenZone\\OZ_Radio_Profiles.json";

    // Сітка ефіру. Пише її МОД (виводячи з профілів), читає НАТИВНИЙ ПАТЧ
    // при старті процесу -- звідси й відкладеність: новий файл діє з
    // наступного запуску сервера, і про це кажуть вголос.
    //
    // Ім'я й розташування узгоджені з native/src/dllmain.cpp: він шукає
    // <profiles>\\OpenZone\\Frequencies.json, а копію поруч із собою лишає
    // запасною. Перейменувати тут -- значить мовчки повернутись до запасної.
    static const string FREQUENCIES      = "$profile:OpenZone\\OZ_Radio_Frequencies.json";
    static const int    SCHEMA_PROFILES  = 1;

    // Куди гравець перетягнув клавіатуру. КЛІЄНТСЬКИЙ файл: $profile: на
    // клієнті -- це його власний профіль, і сервера це не стосується.
    static const string KEYPAD_POS = "$profile:OpenZone\\OZ_Radio_Keypad.json";

    // Клавіші. Обидві оголошені у ВЛАСНОМУ inputs.xml цього мода: ручна рація
    // не модуль КПК, і позичена в сусіда клавіша зникала б разом із ним.
    static const string INPUT_FREQ = "UAOZRadioFreq";
    static const string INPUT_PTT  = "UAOZRadioPtt";

    // Ідентифікатор меню.
    //
    // МАЄ БУТИ МАЛИМ. Виміряно сусіднім модом і записано в OZ_PdaConst: із
    // великим числом EnterScriptedMenu просто повертає NULL, а
    // Mission.CreateScriptedMenu навіть не кличеться -- у лозі видно виклики
    // з ванільними 11 і 17, і жодного з шестизначним. Тому не «беремо високе,
    // щоб ні з ким не зіткнутись», а тиснемось поруч із КПК (131, 132).
    //
    // Реєстру id у рушії немає, тож зіткнення непереборне -- і воно ВЖЕ
    // сталося: 133 виявився зайнятий OZ_LinkMenu ядра, і меню відкривалось
    // чуже, мовчки. Виглядало це як «клавіатура не працює», бо super
    // .CreateScriptedMenu віддавав чужий екземпляр раніше, ніж черга доходила
    // до нашого. Тому OZR_FreqInput після відкриття перевіряє, що екземпляр
    // саме наш, і каже вголос, якщо ні.
    //
    // Зайнято сім'єю OpenZone: 131 КПК, 132 його HUD-редактор, 133 прив'язка.
    static const int    MENU_FREQ  = 134;

    // RPC цього мода. Імена глобальні на весь процес, тому з префіксом.
    static const string RPC_GRID_REQ = "OZR_GridReq";
    static const string RPC_GRID_RES = "OZR_GridRes";
    static const string RPC_PROF_RES = "OZR_ProfRes";
    static const string RPC_TUNE     = "OZR_TuneReq";
    static const string RPC_PTT      = "OZR_PttRadio";
    static const string RPC_AUDIO_RES = "OZR_AudioRes";
}
