// Форма, якою сторінка «Рація» говорить із сервером.
//
// У 3_Game, бо на неї дивляться обидва боки: сервер складає, клієнт читає.
//
// КАНАЛІВ ТУТ БІЛЬШЕ НЕМАЄ. Іменований канал був потрібен, поки частот було
// вісім і числа нічого не значили; після зняття межі ефір міряється тисячами
// ділень, і плата налаштовується так само, як ручна рація, -- числом. Імена ж,
// коли вони знадобляться, будуть річчю ГРАВЦЯ на носії, а не конфігом сервера.

class OZR_RadioState
{
    // Плата вставлена. Без неї сторінки взагалі не буває, але прийти сюди
    // можна саме в мить, коли її витягли.
    bool  HasBoard = false;
    bool  Powered  = false;

    // Дальність -- ВЛАСНА дальність плати з її конфіга. Окремого модуля антени
    // більше немає: плата -- це рація, а антена в рації не окрема річ.
    float RangeM   = 0;

    // Чи йде передача просто зараз.
    bool  Live     = false;

    // На чому стоїть. Індекс -- те, чим оперує рушій; МГц -- те, що читає
    // людина. Возимо обидва, щоб клієнт не рахував частоту сам: сітку він
    // знає, але одне джерело завжди краще за два.
    int   Index    = -1;
    float FreqMHz  = 0;

    // Межі цієї плати -- щоб сторінка могла сказати, куди їй можна, не
    // питаючи окремо.
    float MinMHz   = 0;
    float MaxMHz   = 0;
    float StepMHz  = 0;

    // САМ ЕФІР: нульове ділення й крок між діленнями. Двома числами МГц
    // перетворюється на ділення й назад, і возяться вони тут навмисне.
    //
    // Раніше сторінка брала їх з OZR_ClientGrid -- окремої копії, яку клієнт
    // тягне своїм таймером. Поки та копія не приїде, сторінка ЛАМАЛАСЬ МОВЧКИ
    // й найгіршим можливим чином: намальовані числа були правильні (їх рахує
    // сервер), а «+» і «-» не робили нічого, і будь-яка набрана частота --
    // хоч би й та сама, що на екрані, -- відповідала «поза смугою». Тобто
    // екран казав одне, а кнопки поводились так, ніби ефіру не існує.
    //
    // Тепер джерело одне: та сама відповідь, з якої малюється екран. Ефір і
    // кнопки не можуть розійтись, бо приїхали разом.
    float EtherBase = 0;
    float EtherStep = 0;

    // Книжка частот із носія. Порожньо буває з двох різних причин -- носія
    // немає або він порожній, -- і сторінка розрізняє їх за HasMemory.
    bool  HasMemory = false;
    int   FreeCells  = -1;
}

